(() => {
  'use strict';
  const selector = document.getElementById('target');
  const state = document.getElementById('state');
  const lastSync = document.getElementById('last-sync');
  const nextStep = document.getElementById('next-step');
  const captureMode = document.getElementById('capture-mode');
  const error = document.getElementById('error');
  const result = document.getElementById('result');
  const retry = document.getElementById('retry');
  const disconnect = document.getElementById('disconnect');
  document.getElementById('settings').href = `${globalThis.KARIX_SYNC_CONFIG.agentOrigin}/settings`;
  let busy = false;
  let targets = [];
  let selected = '';
  let globalError = '';
  let actionError = '';
  const key = target => `${target.account}/${target.integration}`;
  const current = () => targets.find(target => key(target) === selected);

  function render() {
    const target = current();
    selector.disabled = busy || !targets.length;
    error.textContent = actionError || target?.error || globalError;
    error.hidden = !error.textContent;
    lastSync.textContent = target?.last_synced_at
      ? new Date(target.last_synced_at * 1000).toLocaleString() : 'Never';
    captureMode.textContent = target?.integration === 'moengage'
      ? (target.capture_active
        ? 'Active MoEngage capture target: unscoped dashboard inventory requests go only to this target for backend workspace binding.'
        : 'Select this target to enable its unscoped MoEngage inventory capture.')
      : 'Karix capture always requires the exact configured WhatsApp identity or RCS bot. No credentials are copied between integrations.';
    if (!target) {
      state.textContent = targets.length ? 'Choose a paired target' : 'No paired targets';
      nextStep.textContent = targets.length
        ? 'Choose the account and integration above. That explicit selection also controls which single MoEngage target can receive unscoped dashboard inventory requests.'
        : 'Open agent Settings, select an account and integration, then connect this extension. Each target is paired separately. Static API and encryption keys are one-time setup in Settings, not generated by this extension.';
    } else if (!target.paired) {
      state.textContent = 'Pairing expired';
      nextStep.textContent = 'Reconnect this exact account and integration in agent Settings. Other paired targets are unaffected.';
    } else if (target.syncing) {
      state.textContent = 'Backend validation in progress';
      nextStep.textContent = 'Wait for backend validation before treating these credentials as synced.';
    } else if (target.error) {
      state.textContent = 'Paired — action required';
      nextStep.textContent = `${target.pending ? 'Retry the captured session below, or capture a fresh request. ' : ''}${target.next_step}`;
    } else if (target.pending) {
      state.textContent = 'Paired — awaiting backend validation';
      nextStep.textContent = 'A complete matching request is available. Retry sync to submit it for backend validation.';
    } else if (target.last_synced_at) {
      state.textContent = 'Last sync validated by backend';
      nextStep.textContent = 'New matching inventory requests sync automatically. This timestamp is historical; use Check status in agent Settings for current validity.';
    } else {
      state.textContent = 'Paired — awaiting matching inventory request';
      nextStep.textContent = target.next_step;
    }
    retry.disabled = busy || !target?.paired || !target.pending || target.syncing;
    disconnect.disabled = busy || !target?.can_disconnect;
  }
  async function refresh() {
    const status = await chrome.runtime.sendMessage({type: 'KARIX_EXTENSION_STATUS'});
    if (!status || !Array.isArray(status.targets)) throw new Error('Could not load extension state. Reload the extension and retry.');
    targets = status.targets;
    globalError = status.error || '';
    selected = targets.some(target => key(target) === status.active_target) ? status.active_target : '';
    selector.replaceChildren();
    const placeholder = new Option(targets.length ? 'Choose a capture target…' : 'No paired targets', '');
    placeholder.disabled = true;
    selector.add(placeholder);
    for (const target of targets) {
      const label = target.integration === 'whatsapp' ? 'WhatsApp' : target.integration === 'rcs' ? 'RCS' : 'MoEngage';
      selector.add(new Option(`${target.account} · ${label}`, key(target)));
    }
    selector.value = selected;
    render();
  }
  function showError(message) {
    actionError = message;
    error.textContent = message;
    error.hidden = false;
  }
  async function action(type) {
    const target = current();
    if (busy || !target) return;
    busy = true;
    actionError = '';
    result.hidden = true;
    render();
    try {
      const response = await chrome.runtime.sendMessage({type, account: target.account, integration: target.integration});
      if (!response || typeof response.ok !== 'boolean' || typeof response.message !== 'string') {
        throw new Error('The extension did not return a result. Reload it and retry.');
      }
      await refresh();
      if (response.ok) {
        result.textContent = response.message;
        result.hidden = false;
      } else showError(response.message);
    } catch (failure) { showError(failure.message || 'Could not contact the extension. Reload it and retry.'); }
    finally { busy = false; render(); }
  }
  selector.addEventListener('change', () => {
    selected = selector.value;
    actionError = '';
    result.hidden = true;
    render();
    if (current()) void action('KARIX_EXTENSION_SELECT');
  });
  retry.addEventListener('click', () => { void action('KARIX_EXTENSION_RETRY'); });
  disconnect.addEventListener('click', () => { void action('KARIX_EXTENSION_DISCONNECT'); });
  chrome.storage.onChanged.addListener((changes, area) => {
    if ((area === 'local' && changes.karixAuthSync) || (area === 'session' && changes.karixAuthSyncSession)) {
      void refresh().catch(failure => showError(failure.message));
    }
  });
  void refresh().catch(failure => showError(failure.message));
})();
